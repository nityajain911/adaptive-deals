/**
 * Generates `strategy_narrative.v1` development option sets from the real engine. No model is called:
 * fetch is replaced so that any attempt fails. The sets are inputs only (an alias per offer and the
 * fact IDs code established); the closed vocabulary that judges a sentence belongs to the validator.
 *
 *   npx tsx --conditions=react-server evaluation-assist/generators/narrative.ts dev
 */
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { createHash } from "node:crypto";

process.env.ADAPTIVE_DEALS_DATA_DIR = mkdtempSync(path.join(os.tmpdir(), "assist-narrative-"));
process.env.ADAPTIVE_DEALS_DEMO_RUN = "synthetic";
for (const key of ["GROQ_API_KEY", "ANTHROPIC_API_KEY"]) delete process.env[key];
globalThis.fetch = async () => {
  throw new Error("No network in the case generator");
};

const STRATEGIES = ["protect_contribution", "preserve_scope", "minimise_cash_exposure", "lower_buyer_commitment"] as const;
type Strategy = (typeof STRATEGIES)[number];
const SET = process.argv[2] ?? "dev";
const FIRST_SEED = SET === "dev" ? 1001 : 2001; // never used by any existing test (tests use 1–200)
const WANTED = SET === "dev" ? 24 : 40;

async function main() {
  const svc = await import("@/lib/service");
  const store = await import("@/lib/economics-store");
  const { illustrativeEconomicsContent } = await import("@/lib/economics-illustrative");
  const { defaultEconomicsContent } = await import("@/lib/economics-default");
  const { genEconomics, rng } = await import("../../tests/helpers/gen");
  // Hold-out sets stay out of version control (only their hashes are committed) until the final run.
  const out = SET === "dev" ? path.join("evaluation-assist", "cases", "strategy_narrative", SET) : path.join("evaluation-assist", "holdout-private", "strategy_narrative", SET);
  mkdirSync(out, { recursive: true });

  const sets: unknown[] = [];
  const skipped: { economics: string; reason: string }[] = [];

  async function optionSets(label: string, content: ReturnType<typeof defaultEconomicsContent>, strategies: readonly Strategy[]) {
    try {
      const issues = await store.saveEconomicsDraft(content);
      if (issues.some((i) => i.level === "error")) return void skipped.push({ economics: label, reason: "invalid economics" });
      await store.activateEconomicsDraft("evaluation-assist generator", new Date().toISOString());
    } catch (e) {
      // Version 1 is already active, so activating identical content is refused; that is not a failure.
      if (!/no change/i.test((e as Error).message)) return void skipped.push({ economics: label, reason: (e as Error).message });
    }
    await svc.resetToSeed();
    await svc.startCase("reduced-scope");
    const s = await svc.sendQuestions();
    for (const q of s.conversation.filter((i) => i.kind === "clarification")) await svc.buyerReply({ inReplyTo: q.id, scriptId: q.refs.questionId === "clar-gst" ? "clar-gst-yes" : "clar-approval-contract" });
    await svc.adoptRepliesAsAnswers();
    for (const strategy of strategies) {
      if (sets.length >= WANTED) return;
      await svc.setStrategy(strategy);
      const cur = await svc.getState();
      const view = svc.strategyViewOf(cur, await svc.currentOutcome(cur));
      const compared = view.mode === "standard" ? view.ranked : view.discounted;
      if (compared.length < 2) {
        skipped.push({ economics: label, reason: `${strategy}: ${compared.length} offer(s) compared` });
        continue;
      }
      const ids = compared.map((o) => o.structure.id).sort();
      const alias = (id: string) => String.fromCharCode(65 + ids.indexOf(id));
      const id = `ns-${SET}-${String(sets.length + 1).padStart(2, "0")}`;
      sets.push({
        id,
        task: "strategy_narrative.v1",
        set: SET,
        authoredBy: "generated by the real engine; economics and strategy chosen by the coding agent",
        source: { caseId: "reduced-scope", economics: label, strategy, mode: view.mode },
        input: {
          strategy,
          offers: ids.map((sid) => ({ alias: alias(sid), factIds: view.facts[sid] ?? [] })),
        },
        truth: { shownOrder: compared.map((o) => alias(o.structure.id)) },
      });
    }
  }

  if (SET === "dev") {
    await optionSets("version-1", defaultEconomicsContent(), STRATEGIES);
    await optionSets("illustrative", illustrativeEconomicsContent(), STRATEGIES);
  }
  for (let seed = FIRST_SEED; sets.length < WANTED && seed < FIRST_SEED + 400; seed++) {
    const strategy = STRATEGIES[seed % STRATEGIES.length]!;
    await optionSets(`seed-${seed}`, genEconomics(rng(seed)), [strategy]);
  }

  for (const item of sets as { id: string }[]) writeFileSync(path.join(out, `${item.id}.json`), JSON.stringify(item, null, 2) + "\n");
  const meta = { set: SET, generated: sets.length, wanted: WANTED, firstSeed: FIRST_SEED, skippedCount: skipped.length, skipped: skipped.slice(0, 60) };
  writeFileSync(path.join(out, "_generation.json"), JSON.stringify(meta, null, 2) + "\n");
  console.log(JSON.stringify({ ...meta, skipped: undefined }), createHash("sha256").update(JSON.stringify(sets)).digest("hex").slice(0, 12));
}
main().catch((e) => { console.error(e); process.exit(1); });
